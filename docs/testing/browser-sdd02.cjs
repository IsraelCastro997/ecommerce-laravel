const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { mkdir } = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(process.env.SDD_PLAYWRIGHT_MODULE || 'playwright-core');

const base = 'http://127.0.0.1:8000';
const evidence = path.join(__dirname, '..', 'evidence', 'sdd-02');

async function main() {
    await mkdir(evidence, { recursive: true });
    const browser = await chromium.launch();
    try {
        const context = await browser.newContext({ viewport: { width: 1440, height: 1050 }, colorScheme: 'light' });
        const page = await context.newPage();
        const errors = [];
        const failures = [];
        page.setDefaultTimeout(15000);
        page.on('pageerror', (error) => errors.push(error.message));
        page.on('response', (response) => {
            if (response.status() >= 400 && response.url().startsWith(base)) failures.push(`${response.status()} ${response.url()}`);
        });

        const role = (type, name) => page.getByRole(type, { name, exact: true });
        const label = (name) => page.getByLabel(name, { exact: true });
        const ready = () => role('heading', 'El camino empieza afuera.').waitFor();
        const quantity = (product) => page.getByLabel('Cantidad de ' + product, { exact: true }).textContent();
        const openCart = () => page.getByRole('button', { name: /^Abrir carrito/ }).click();
        const snapshot = (name, fullPage = true) => page.screenshot({ path: path.join(evidence, name + '.png'), fullPage, animations: 'disabled' });
        const noOverflow = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
        const add = async (product) => {
            await role('button', product).click();
            await role('button', 'Agregar al carrito demo').click();
            await role('heading', 'Tu carrito').waitFor();
        };

        await page.goto(base);
        await ready();
        await page.keyboard.press('Tab');
        assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), 'Saltar al contenido');
        const mochila = 'Mochila Sierra 35 L';
        const botella = 'Botella Bruma 750 ml';
        await role('button', mochila).click();
        assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Cerrar');
        await page.keyboard.press('Escape');
        assert.equal(await page.evaluate(() => document.activeElement.textContent.trim()), mochila);
        await add(mochila);
        assert.equal(await quantity(mochila), '1');
        await page.keyboard.press('Escape');
        await add(mochila);
        assert.equal(await quantity(mochila), '2');
        for (let i = 2; i < 9; i++) await role('button', 'Agregar una unidad de ' + mochila).click();
        assert.equal(await quantity(mochila), '9');
        assert.equal(await role('button', 'Agregar una unidad de ' + mochila).isDisabled(), true);
        await role('button', 'Quitar una unidad de ' + mochila).click();
        assert.equal(await quantity(mochila), '8');
        await page.keyboard.press('Escape');
        await add(botella);
        assert.equal(await quantity(botella), '1');
        await role('button', 'Eliminar ' + botella).click();
        assert.equal(await label('Cantidad de ' + botella).count(), 0);
        await page.keyboard.press('Escape');
        await role('button', 'Linterna Lumbre 300').click();
        assert.equal(await role('button', 'Agregar al carrito demo').isDisabled(), true);
        await page.keyboard.press('Escape');
        await role('combobox', 'Moneda').selectOption('USD');
        await role('button', 'Vista en lista').click();

        await page.setViewportSize({ width: 320, height: 850 });
        await noOverflow();
        await page.reload();
        await ready();
        await noOverflow();
        assert.equal(await role('combobox', 'Moneda').inputValue(), 'USD');
        await openCart();
        assert.equal(await quantity(mochila), '8');
        await snapshot('carrito-320', false);
        const availability = label('Estado de disponibilidad (demo)');
        await availability.selectOption('loading');
        await page.getByText('Comprobación de disponibilidad en curso · Simulación', { exact: true }).waitFor();
        assert.equal(await role('button', 'Ver checkout demo').isDisabled(), true);
        await availability.selectOption('unavailable');
        await page.getByRole('alert').filter({ hasText: 'no hay disponibilidad suficiente' }).waitFor();
        await snapshot('carrito-disponibilidad-320', false);
        assert.equal(await role('button', 'Ver checkout demo').isDisabled(), true);
        await availability.selectOption('ready');
        await role('button', 'Ver checkout demo').click();
        await label('Correo del comprador (demo)').waitFor();
        await page.getByText('Resumen de artículos', { exact: true }).waitFor();
        assert.equal(await role('button', 'Continuar al pago').isDisabled(), true);
        await page.keyboard.press('Escape');
        console.log('PASS carrito demo: alta doble, cantidad, límite, eliminar, agotado, recarga, moneda, carga, error y checkout sin pago');

        assert.equal((await page.request.get(base + '/admin')).status(), 404);
        await page.goto(base + '/dashboard');
        await page.waitForURL('**/login');
        await role('link', 'Crear cuenta').click();
        const email = `qa-sdd02-${randomUUID().slice(0, 10)}@example.test`;
        const password = `Local-QA-${randomUUID()}`;
        await label('Nombre').fill('Cuenta de prueba SDD-02');
        await label('Correo electrónico').fill(email);
        await label('Contraseña').fill(password);
        await label('Confirmar contraseña').fill(password);
        await role('button', 'Crear cuenta').click();
        await page.waitForURL('**/dashboard');
        await role('heading', 'Mi cuenta').waitFor();
        assert.equal((await page.request.get(base + '/admin')).status(), 404);
        await noOverflow();
        await label('Moneda preferida').selectOption('MXN');
        const inertiaVisit = page.waitForRequest((request) => request.url() === base + '/' && request.headers()['x-inertia'] === 'true');
        await page.getByRole('link', { name: 'Volver a la tienda' }).click();
        await inertiaVisit;
        await ready();
        assert.equal(await role('combobox', 'Moneda').inputValue(), 'MXN');
        await openCart();
        assert.equal(await quantity(mochila), '8');
        await role('button', 'Vaciar carrito de demostración').click();
        await page.getByText('Tu carrito de demostración está vacío.', { exact: true }).waitFor();
        await page.keyboard.press('Escape');
        await page.reload();
        await ready();
        await openCart();
        await page.getByText('Tu carrito de demostración está vacío.', { exact: true }).waitFor();
        await page.keyboard.press('Escape');
        await page.evaluate(() => localStorage.setItem('refugio:demo-cart:v1', 'archivo incorrecto'));
        await page.reload();
        await ready();
        await openCart();
        await page.getByText('Tu carrito de demostración está vacío.', { exact: true }).waitFor();
        await page.keyboard.press('Escape');
        await page.evaluate(() => localStorage.setItem('refugio:demo-cart:v1', JSON.stringify({ 'MO-035': 110, 'IL-300': 2, INVENTADO: 1 })));
        await page.reload();
        await ready();
        await openCart();
        assert.equal(await quantity(mochila), '9');
        assert.equal(await page.getByRole('dialog').getByText('Linterna Lumbre 300', { exact: true }).count(), 0);
        await role('button', 'Vaciar carrito de demostración').click();
        await page.keyboard.press('Escape');
        console.log('PASS persistencia: navegación Inertia, recarga, limpieza, almacenamiento inválido, SKU agotado y moneda de cuenta');

        await page.setViewportSize({ width: 768, height: 970 });
        await noOverflow();
        await role('link', 'Mi cuenta').click();
        await role('heading', 'Mi cuenta').waitFor();
        await role('button', 'Pedidos').click();
        await page.getByText('RF-1042 · Preparando', { exact: true }).click();
        await page.getByText('Preparación de envío (ejemplo)', { exact: true }).waitFor();
        await role('button', 'Direcciones').click();
        assert.equal(await role('button', 'Añadir dirección · Pendiente').isDisabled(), true);
        await role('button', 'Mi cuenta').click();
        await page.getByRole('link', { name: 'Editar perfil' }).click();
        await role('heading', 'Información del perfil').waitFor();
        await page.goBack();
        await role('heading', 'Mi cuenta').waitFor();
        await role('button', 'Administración demo').click();
        await role('heading', 'Panel de administración').waitFor();
        await role('button', 'Productos').click();
        await page.getByRole('table', { name: 'Registros de demostración · Productos' }).waitFor();
        await label('Buscar en productos').fill('linterna');
        await page.getByRole('rowheader', { name: 'IL-300', exact: true }).waitFor();
        assert.equal(await page.getByRole('rowheader', { name: 'MO-035', exact: true }).count(), 0);
        await label('Buscar en productos').fill('inexistente');
        await page.getByText('Sin registros de demostración para los filtros actuales.', { exact: true }).waitFor();
        await label('Buscar en productos').fill('');
        const adminState = label('Estado de demostración');
        await adminState.selectOption('loading');
        await page.getByText('Cargando datos de ejemplo…', { exact: true }).waitFor();
        await adminState.selectOption('error');
        await page.getByRole('alert').waitFor();
        await role('button', 'Restablecer la demostración').click();
        await role('button', 'Nuevo producto demo').click();
        await page.getByRole('dialog', { name: 'Crear producto demo' }).waitFor();
        assert.equal(await role('button', 'Guardar cambios').isDisabled(), true);
        await page.keyboard.press('Escape');
        await role('button', 'Editar MO-035 Mochila Sierra 35 L').click();
        assert.equal(await label('Nombre').inputValue(), mochila);
        await page.keyboard.press('Escape');
        await page.setViewportSize({ width: 1440, height: 1050 });
        await noOverflow();
        await snapshot('administracion-productos-desktop');
        await role('button', 'Pedidos y Stripe').click();
        await label('Fecha desde').fill('2026-11-15');
        await page.getByRole('rowheader', { name: 'Pedido', exact: true }).waitFor();
        assert.equal(await page.getByRole('rowheader', { name: 'Pago', exact: true }).count(), 0);
        await role('button', 'Precios').click();
        await page.setViewportSize({ width: 320, height: 850 });
        await noOverflow();
        const prices = role('region', 'Tabla de Precios con desplazamiento horizontal');
        assert.equal(await prices.evaluate((element) => element.scrollWidth > element.clientWidth), true);
        await snapshot('administracion-320');

        assert.deepEqual(errors, []);
        assert.deepEqual(failures, []);
        console.log('PASS cuenta y administración demo: registro, perfil, historial, filtros, tablas, diálogos y diseño 320/768/1440 px');
        console.log('PASS /admin no publicado (HTTP 404 como invitado y autenticado); sin excepciones JS ni errores HTTP en flujos esperados');
    } finally {
        await browser.close();
    }
}

main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
});
