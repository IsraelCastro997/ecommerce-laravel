const { chromium } = require(process.env.SDD_PLAYWRIGHT_MODULE || 'playwright-core');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

(async () => {
    const browser = await chromium.launch({ headless: true });
    const base = process.env.SDD_BASE_URL || 'http://127.0.0.1:8000';
    const output = path.join(__dirname, 'screenshots', 'catalog-review');
    fs.mkdirSync(output, { recursive: true });
    const errors = [], checks = [];
    const connect = async (width) => {
        const context = await browser.newContext({ viewport: { width, height: 1000 } });
        const page = await context.newPage();
        page.on('pageerror', e => errors.push(e.message));
        await page.goto(base + '/catalogo');
        await page.waitForFunction(() => Boolean(window.Alpine?.store('shop')));
        await page.evaluate(() => document.fonts.ready);
        return { context, page };
    };
    try {
        const { context, page } = await connect(1440);
        assert.equal(await page.locator('.product-card').count(), 4);
        assert.ok(await page.evaluate(() => document.fonts.check('600 20px "Bricolage Grotesque"')));
        await page.screenshot({ path: path.join(output, 'catalog-desktop.png'), fullPage: true });
        await page.getByRole('group', { name: 'Categorías de productos' }).getByRole('button', { name: 'Mochilas', exact: true }).click();
        assert.equal(await page.locator('.product-card').count(), 1);
        await page.getByRole('searchbox', { name: 'Buscar', exact: true }).fill('inexistente');
        await page.getByRole('heading', { name: 'No encontramos ese equipo.' }).waitFor();
        await page.screenshot({ path: path.join(output, 'catalog-empty.png'), fullPage: true });
        await page.getByRole('button', { name: 'Ver todos los productos', exact: false }).click();
        assert.equal(await page.locator('.product-card').count(), 4);
        await page.getByLabel('Solo disponibles', { exact: true }).check();
        assert.equal(await page.locator('.product-card').count(), 3);
        await page.getByRole('button', { name: 'Quitar filtro: Disponibles', exact: true }).click();
        await page.getByRole('combobox', { name: 'Ordenar productos' }).selectOption('asc');
        assert.match(await page.locator('.product-card h3').first().innerText(), /Botella/);
        await page.getByRole('button', { name: 'Cambiar vista', exact: true }).click();
        assert.ok(await page.locator('.catalog-product-grid').evaluate(el => el.classList.contains('is-list')));
        await page.screenshot({ path: path.join(output, 'catalog-list.png'), fullPage: true });
        await page.getByRole('button', { name: 'Cambiar vista', exact: true }).click();
        await page.getByRole('button', { name: 'Vista rápida de Mochila Sierra 35 L', exact: true }).click();
        await page.getByRole('dialog').waitFor();
        await page.screenshot({ path: path.join(output, 'catalog-quickview.png') });
        await page.keyboard.press('Escape');
        assert.equal(await page.getByRole('dialog').count(), 0);
        assert.equal(await page.evaluate(() => document.activeElement.getAttribute('aria-label')), 'Vista rápida de Mochila Sierra 35 L');
        await page.getByRole('button', { name: 'Vista rápida de Mochila Sierra 35 L', exact: true }).click();
        await page.getByRole('dialog').getByRole('button', { name: 'Agregar a bolsa', exact: true }).click();
        await page.getByRole('button', { name: 'Cerrar vista rápida', exact: true }).click();
        assert.equal(await page.evaluate(() => window.Alpine.store('shop').count), 1);
        await page.getByRole('button', { name: 'Cerrar aviso', exact: true }).click();
        await page.route('https://images.example.invalid/**', route => route.abort());
        const brokenImage = page.waitForRequest('https://images.example.invalid/missing.jpg');
        await page.evaluate(() => { window.Alpine.store('shop').products[0].image_url = 'https://images.example.invalid/missing.jpg'; });
        await brokenImage;
        await page.waitForFunction(() => !document.querySelector('img[src="https://images.example.invalid/missing.jpg"]'));
        checks.push('desktop: filtros, búsqueda, estado vacío, orden, lista, vista rápida, bolsa, foco e imagen fallida');
        await page.goto(base + '/productos/MO-035');
        await page.getByRole('heading', { name: 'Mochila Sierra 35 L' }).waitFor();
        await page.screenshot({ path: path.join(output, 'product-desktop.png'), fullPage: true });
        await page.goto(base + '/');
        await page.locator('.product-card').first().waitFor();
        await page.screenshot({ path: path.join(output, 'home-desktop.png'), fullPage: true });
        await context.close();
        for (const width of [320, 390, 768]) {
            const { context, page } = await connect(width);
            assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'Catalog overflow at ' + width);
            await page.screenshot({ path: path.join(output, `catalog-${width}.png`), fullPage: true });
            const filters = page.getByRole('button', { name: 'Filtros', exact: true });
            assert.equal(await filters.getAttribute('aria-expanded'), 'false');
            await filters.click();
            await page.getByLabel('Solo disponibles', { exact: true }).check();
            assert.equal(await page.locator('.product-card').count(), 3);
            await page.getByRole('button', { name: 'Cerrar filtros', exact: true }).click();
            await page.getByRole('button', { name: 'Quitar filtro: Disponibles', exact: true }).click();
            await page.getByRole('button', { name: 'Vista rápida de Mochila Sierra 35 L', exact: true }).click();
            await page.getByRole('dialog').waitFor();
            assert.ok(await page.getByRole('dialog').evaluate(el => el.getBoundingClientRect().width <= innerWidth));
            await page.screenshot({ path: path.join(output, `quickview-${width}.png`) });
            await page.keyboard.press('Escape');
            await page.goto(base + '/productos/MO-035');
            await page.getByRole('heading', { name: 'Mochila Sierra 35 L' }).waitFor();
            assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
            await page.screenshot({ path: path.join(output, `product-${width}.png`), fullPage: true });
            checks.push(`${width}px: catálogo, filtros, vista rápida y detalle sin desbordamiento`);
            await context.close();
        }
        assert.deepEqual(errors, []);
        const result = { status: 'PASS', checks, browserErrors: errors, screenshots: fs.readdirSync(output).filter(f => f.endsWith('.png')) };
        fs.writeFileSync(path.join(__dirname, 'catalog-review-result.json'), JSON.stringify(result, null, 2) + '\n');
        console.log(JSON.stringify(result));
    } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
